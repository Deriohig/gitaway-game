// look-grid.mjs  --  labelled N-up comparison sheets of captured views (moods, tone mappers, ...) (NO deps).
// =============================================================================
// Usage:  node look-grid.mjs --out <phase>/<name>.png [--views full,farm] [--max-mb 1.45] [--w 560] "<label>=<dir>" ...
//   e.g.  node look-grid.mjs --out phase1_moods/sheet_moods_full.png --views full \
//           "GOLDEN AFTERNOON=phase1/raw" "SOFT MORNING=phase1_moods/raw/morning" "DUSK=phase1_moods/raw/dusk" "GAME (CURRENT) REF=phase1_lambert/raw"
//         node look-grid.mjs --out phase1_tonemap/sheet_tonemap.png --views full,farm "AGX=phase1_tonemap/raw/agx" "NEUTRAL=phase1_tonemap/raw/neutral"
// Columns = the label=dir entries (dirs relative to art/screenshots, holding <view>.png [+ <view>_mask.png] from
// look-capture.mjs --out), rows = views. Each panel: label + view on top, metrics.mjs footer (terrainSat / meanLum / lumStd /
// darkest, then the grass / yellowGreen / foliage / rock / path bands). Writes <out> (downscaled until <= --max-mb) and
// <out minus .png>.md / .json with the full metrics table.
// =============================================================================
import fs from 'node:fs';
import path from 'node:path';
import { readPNG, encodePNG, blank, resizeBilinear, blit } from './lib/png.mjs';
import { drawText } from './lib/label.mjs';
import { imageMetrics } from './metrics.mjs';
import { ART_DIR } from './lib/paths.mjs';

const SHOTS = path.join(ART_DIR, 'screenshots'), BG = [38, 36, 34, 255], C_LABEL = [235, 215, 160], C_TEXT = [225, 220, 205];
const a = process.argv.slice(2);
let out = null, views = ['full'], maxMB = 1.45, W0 = 560;
const cols = [];
for (let i = 0; i < a.length; i++) {
  if (a[i] === '--out') out = a[++i]; else if (a[i] === '--views') views = a[++i].split(','); else if (a[i] === '--max-mb') maxMB = +a[++i]; else if (a[i] === '--w') W0 = +a[++i];
  else { const k = a[i].indexOf('='); if (k > 0) cols.push({ label: a[i].slice(0, k), dir: path.join(SHOTS, a[i].slice(k + 1)) }); }
}
if (!out || !cols.length) { console.error('usage: node look-grid.mjs --out <phase>/<name>.png [--views a,b] "<label>=<dir>" ...'); process.exit(2); }
const outFile = path.join(SHOTS, out); fs.mkdirSync(path.dirname(outFile), { recursive: true });
const load = (f) => (fs.existsSync(f) ? readPNG(f) : null);
const cells = views.map((v) => cols.map((c) => { const img = load(path.join(c.dir, v + '.png')); if (!img) throw new Error('missing ' + path.join(c.dir, v + '.png'));
  return { v, c, img, m: imageMetrics(img, load(path.join(c.dir, v + '_mask.png'))) }; }));
const pc = (x) => (x * 100).toFixed(1) + '%';
const L1 = (m) => `SAT ${m.terrainSat.toFixed(3)} LUM ${m.meanLum.toFixed(3)} SD ${m.lumStd.toFixed(3)} DARK ${m.darkest.toFixed(3)}`;
const L2 = (m) => `GRN ${pc(m.bands.grass)} YG ${pc(m.bands.yellowGreen)} FOL ${pc(m.bands.foliage)} ROCK ${pc(m.bands.rock)} PATH ${pc(m.bands.path)}`;
let s = 1, buf = null, img = null;
for (let k = 0; k < 14; k++) {
  const PAD = 12, LABEL = 26, FOOT = 44, W = Math.round(W0 * s), H = Math.round(W * cells[0][0].img.height / cells[0][0].img.width), maxCh = Math.floor(W / 12);
  img = blank(PAD + cols.length * (W + PAD), PAD + views.length * (LABEL + H + FOOT + PAD), BG);
  cells.forEach((row, r) => row.forEach((cell, q) => { const x = PAD + q * (W + PAD), y = PAD + r * (LABEL + H + FOOT + PAD);
    drawText(img, x, y, `${cell.c.label}  ${cell.v}`.slice(0, maxCh), 2, C_LABEL);
    blit(img, resizeBilinear(cell.img, W, H), x, y + LABEL);
    drawText(img, x, y + LABEL + H + 6, L1(cell.m).slice(0, maxCh), 2, C_TEXT); drawText(img, x, y + LABEL + H + 24, L2(cell.m).slice(0, maxCh), 2, C_TEXT); }));
  buf = encodePNG(img, { rgb: true, level: 9 }); if (buf.length <= maxMB * 1048576) break; s *= 0.92;
}
fs.writeFileSync(outFile, buf);
const md = [`# ${path.basename(out)}`, '', `Generated by \`art/scripts/look-grid.mjs\`. Metrics: \`metrics.mjs\` (terrainSat = island pixels when a mask exists; bands = share of all pixels).`, '',
  '| view | column | terrainSat | meanLum | lumStd | darkest | darkest p0.1 | grass | yellowGreen | foliage | rock | path | cool |', '|---|---|---|---|---|---|---|---|---|---|---|---|---|'];
const json = {};
for (const row of cells) for (const { v, c, m } of row) { const b = m.bands;
  md.push(`| ${v} | ${c.label} | ${m.terrainSat.toFixed(3)} | ${m.meanLum.toFixed(3)} | ${m.lumStd.toFixed(3)} | ${m.darkest.toFixed(3)} | ${m.darkestP01.toFixed(3)} | ${pc(b.grass)} | ${pc(b.yellowGreen)} | ${pc(b.foliage)} | ${pc(b.rock)} | ${pc(b.path)} | ${pc(b.cool)} |`);
  (json[v] = json[v] || {})[c.label] = m; }
fs.writeFileSync(outFile.replace(/\.png$/, '.md'), md.join('\n') + '\n'); fs.writeFileSync(outFile.replace(/\.png$/, '.json'), JSON.stringify(json, null, 1) + '\n');
console.log(`  ${out} ${img.width}x${img.height} ${(buf.length / 1048576).toFixed(2)} MB (+ .md / .json)`);
