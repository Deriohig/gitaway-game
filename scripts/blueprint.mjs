// Copies the island blueprint's piece data from the art session's
// art/config/blueprint.pieces.json into src/world/blueprint.data.ts, keeping
// only what the game reads: each piece's docked position, outline, MAIN θ
// range, flat zones, coast anchors (with the ground kept clear beside one, its
// shed patch) and water. Run it after the art session
// changes the JSON (`npm run blueprint`); src/world/blueprint.test.ts fails
// until the two agree.
//
//   node scripts/blueprint.mjs           write the data file
//   node scripts/blueprint.mjs --check   exit 1 if it is out of date

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(root, 'art/config/blueprint.pieces.json')
const TARGET = path.join(root, 'src/world/blueprint.data.ts')

/** The trimmed piece data, in the order the blueprint lists the pieces. */
export function trimBlueprint(json) {
  const pieces = {}
  for (const id of json.order) {
    const p = json.pieces[id]
    const zones = id === 'main' ? [] : (p.flatZones ?? [])
    pieces[id] = {
      id,
      dockedPosition: p.dockedPosition,
      depth: p.depth,
      outline: p.outline,
      mainTheta: p.mainThetaRange ? p.mainThetaRange.deg : null,
      flatZones: zones.map((z) => ({ id: z.id, kind: z.kind, at: z.at, r: z.r, flat: z.flat, level: z.level })),
      anchors: (p.openCoastAnchors ?? []).map((a) => ({
        id: a.id,
        at: a.local,
        ...(a.outward ? { outward: a.outward } : {}),
        ...(a.y !== undefined ? { y: a.y } : {}),
        ...(a.shedPatch ? { shedPatch: { at: a.shedPatch.at, r: a.shedPatch.r } } : {}),
      })),
      water: p.water ?? null,
    }
  }
  return { format: json.format, order: json.order, pieces }
}

function render(data) {
  // One piece per block, each list on one line: compact, and a change to one
  // piece reads as a change to that piece in a diff.
  const lines = [
    '// Generated by scripts/blueprint.mjs from art/config/blueprint.pieces.json.',
    "// Don't edit it by hand: ask the art session to change the blueprint, then run `npm run blueprint`.",
    '',
    "import type { BlueprintData } from './blueprint'",
    '',
    'export const BLUEPRINT_DATA: BlueprintData = {',
    `  format: ${JSON.stringify(data.format)},`,
    `  order: ${JSON.stringify(data.order)},`,
    '  pieces: {',
  ]
  for (const id of data.order) {
    const p = data.pieces[id]
    lines.push(`    ${id}: {`)
    for (const [key, value] of Object.entries(p)) lines.push(`      ${key}: ${JSON.stringify(value)},`)
    lines.push('    },')
  }
  lines.push('  },', '}', '')
  return lines.join('\n')
}

export function generate() {
  return render(trimBlueprint(JSON.parse(fs.readFileSync(SOURCE, 'utf8'))))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate()
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : ''
    if (now !== text) {
      console.error('src/world/blueprint.data.ts is out of date: run `npm run blueprint`.')
      process.exit(1)
    }
    console.log('src/world/blueprint.data.ts matches the blueprint.')
  } else {
    fs.writeFileSync(TARGET, text)
    console.log(`wrote ${path.relative(root, TARGET)} (${(text.length / 1024).toFixed(1)} KB)`)
  }
}
