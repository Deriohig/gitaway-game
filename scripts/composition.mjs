// Copies the art session's composition (art/config/composition.pieces.json:
// the trees, shrubs, rocks, flowers and grass on each piece, its path runs,
// and the reeds it stands by a piece's water) into the game, keeping only what
// the game reads:
//
//   src/world/composition.meta.ts  each asset's file (and its far version's, for
//                                  a tree) and lift, how many of each
//                                  kind every piece has, and each piece's path
//                                  runs with the pieces they need: small, read
//                                  when the game starts
//   src/world/composition.data.ts  every item, piece by piece, and the reeds
//                                  (outside the categories, on the pieces that
//                                  have them: the farm pond's): large, loaded
//                                  only once the composition or the reeds are
//                                  drawn
//
// Run it after the art session changes the JSON (`npm run composition`);
// src/world/composition.test.ts fails until the two agree.
//
//   node scripts/composition.mjs           write the data files
//   node scripts/composition.mjs --check   exit 1 if they are out of date

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(root, 'art/config/composition.pieces.json')
const META = path.join(root, 'src/world/composition.meta.ts')
const DATA = path.join(root, 'src/world/composition.data.ts')

const HEADER = [
  '// Generated by scripts/composition.mjs from art/config/composition.pieces.json.',
  "// Don't edit it by hand: ask the art session to change the composition, then run `npm run composition`.",
]

/**
 * What the game reads of the composition, in the JSON's own order: each asset's far version too, where it has one,
 * and the reeds of each piece that has them (`pieces.<id>.reeds`, outside the categories: see the JSON's
 * `draw.reeds`), each as { x, z, height, head }.
 */
export function trimComposition(json) {
  const assets = Object.fromEntries(
    Object.entries(json.assets).map(([id, a]) => [id, { category: a.category, file: a.file, ...(a.far ? { far: a.far } : {}), yOffset: a.yOffset }]),
  )
  const counts = {}
  const paths = {}
  const items = {}
  const reeds = {}
  for (const [id, p] of Object.entries(json.pieces)) {
    counts[id] = Object.fromEntries(json.categories.map((c) => [c, p[c].length]))
    paths[id] = p.paths.map((r) => ({ id: r.id, leadsTo: r.leadsTo, needs: r.needs }))
    items[id] = Object.fromEntries(json.categories.map((c) => [c, p[c]]))
    if (p.reeds) reeds[id] = p.reeds.map(({ x, z, height, head }) => ({ x, z, height, head }))
  }
  return { format: json.format, categories: json.categories, assets, counts, paths, items, reeds }
}

function renderMeta(data) {
  const lines = [...HEADER, '', "import type { CompositionMeta } from './composition'", '', 'export const COMPOSITION_META: CompositionMeta = {']
  lines.push(`  format: ${JSON.stringify(data.format)},`, `  categories: ${JSON.stringify(data.categories)},`, '  assets: {')
  for (const [id, a] of Object.entries(data.assets)) lines.push(`    ${id}: ${JSON.stringify(a)},`)
  lines.push('  },', '  counts: {')
  for (const [id, c] of Object.entries(data.counts)) lines.push(`    ${id}: ${JSON.stringify(c)},`)
  lines.push('  },', '  paths: {')
  for (const [id, runs] of Object.entries(data.paths)) {
    lines.push(`    ${id}: [`)
    for (const r of runs) lines.push(`      ${JSON.stringify(r)},`)
    lines.push('    ],')
  }
  lines.push('  },', '}', '')
  return lines.join('\n')
}

function renderData(data) {
  // One item per line: a change to one item reads as a change to that item in a diff.
  const lines = [
    ...HEADER,
    '// It is large, so the game loads it only once the composition or the reeds are drawn (see composition.ts).',
    '',
    "import type { CompositionItems, CompositionReeds } from './composition'",
    '',
  ]
  lines.push('export const COMPOSITION_ITEMS: CompositionItems = {')
  for (const [id, piece] of Object.entries(data.items)) {
    lines.push(`  ${id}: {`)
    for (const [c, list] of Object.entries(piece)) {
      if (!list.length) {
        lines.push(`    ${c}: [],`)
        continue
      }
      lines.push(`    ${c}: [`)
      for (const item of list) lines.push(`      ${JSON.stringify(item)},`)
      lines.push('    ],')
    }
    lines.push('  },')
  }
  lines.push('}', '')
  lines.push(
    "// The reeds the art stands by a piece's water, outside the categories: the game draws them with its own Reeds",
    '// (the farm pond\'s: see water/pondDressing.ts teardropReeds).',
    'export const COMPOSITION_REEDS: CompositionReeds = {',
  )
  for (const [id, list] of Object.entries(data.reeds)) {
    lines.push(`  ${id}: [`)
    for (const reed of list) lines.push(`    ${JSON.stringify(reed)},`)
    lines.push('  ],')
  }
  lines.push('}', '')
  return lines.join('\n')
}

export function generate() {
  const data = trimComposition(JSON.parse(fs.readFileSync(SOURCE, 'utf8')))
  return [
    [META, renderMeta(data)],
    [DATA, renderData(data)],
  ]
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = generate()
  if (process.argv.includes('--check')) {
    const stale = files.filter(([file, text]) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '') !== text)
    for (const [file] of stale) console.error(`${path.relative(root, file)} is out of date: run \`npm run composition\`.`)
    if (stale.length) process.exit(1)
    console.log('src/world/composition.meta.ts and composition.data.ts match the composition.')
  } else {
    for (const [file, text] of files) {
      fs.writeFileSync(file, text)
      console.log(`wrote ${path.relative(root, file)} (${(text.length / 1024).toFixed(1)} KB)`)
    }
  }
}
